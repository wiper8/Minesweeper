test_that("independant_clusters fonctionne pour des hypothesis = FALSE", {
  grid <- matrix(
    c(
      -5, 4, -5, 3, -2, 1,
      -5, -1, -5, -1, -1, 2,
      -5, -1, -1, 2, 2, -5,
      -5, 3, 2, -2, 2, 1,
      2, -1, -2, -1, 3, 1,
      1, -2, 3, -5, -5, 1
    ),
    nrow = 6,
    byrow = TRUE
  )
  solved_around <- init_solved_around(grid)
  expect_equal(
    independant_clusters(grid, solved_around, mines_left = 5),
    list(list(
      grid = grid,
      solved_around = solved_around,
      bornes_mines = c(0, 11),
      possible = rep("NA", 12),
      last_success_mines = NA
    ))
  )
})

